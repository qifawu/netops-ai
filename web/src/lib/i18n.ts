/** 中英切换的框架。**只管前端自己写死的文案**（导航/按钮/标题这些）——
 *  后端拼出来的字符串（`/api/status` 的徽标文字、结论正文、告警一句话总结这些）
 *  是 AI/Python 生成的，不在这个字典里，需要另一套"生成时/展示时按需翻译"的机制，
 *  跟这里的静态字典是两件事，别混在一起做。
 *
 *  用法：`const t = useT(); t("nav.overview")`——key 缺了会显示 key 本身（不会崩、
 *  不会静默显示中文），方便一眼看出哪条还没翻。
 */

export type Lang = "zh" | "en";

export const LANG_STORAGE_KEY = "netops-ai:lang";

export function loadStoredLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY);
    return v === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function storeLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // 存不了就算了，不影响这一次会话内切换
  }
}

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: "zh",
  setLang: () => {},
});

export function useLang(): Lang {
  return useContext(LangContext).lang;
}

export function useSetLang(): (l: Lang) => void {
  return useContext(LangContext).setLang;
}

