export type DictKey = keyof typeof dict;

export function translate(lang: Lang, key: DictKey): string {
  const entry: Partial<Record<Lang, string>> | undefined = dict[key];
  if (!entry) return key;
  // 不能用 `||` 兜底——有些条目故意把某个语言写成空字符串（比如中文单位"条"英文不需要
  // 单位词），`||` 会把合法的空字符串当成"没翻译"退回中文，用 `in`/`undefined` 精确判断。
  if (lang in entry && entry[lang] !== undefined) return entry[lang] as string;
  return entry.zh ?? key;
}

/** 带占位符的条目（`{calls}` 这种）用这个，`translate()` 只管查字典不管插值。 */
export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

export function useT(): (key: DictKey) => string {
  const lang = useLang();
  return (key: DictKey) => translate(lang, key);
}
